// Settings → Hermes settings: Hermes's options in groups and in words, with checked input and a way back to the default.
const { WEB, calls, check, sleep } = require('../lib.cjs')

module.exports = async t => {
  const { browser } = t
  const pg = await browser.newPage({ viewport: { width: 375, height: 812 } })
  await pg.goto(WEB + '/')
  await pg.getByPlaceholder('Message Hermux').waitFor({ timeout: 15000 })
  await pg.getByRole('button', { name: /^Sessions/ }).click()
  await pg.locator('.nav-tile', { hasText: 'Settings' }).click()
  await pg.locator('.set-row', { hasText: 'Hermux settings' }).click()
  await pg.locator('.screen .title', { hasText: 'Hermux settings' }).waitFor({ timeout: 5000 })
  await pg.locator('.set-row', { hasText: 'Retries before a fallback' }).waitFor({ timeout: 5000 })
  const groups = await pg.locator('.set-heading').allInnerTexts()
  check(['Memory', 'Long chats', 'Sub-agents', 'Safety and privacy'].every(g => groups.some(x => x.toLowerCase() === g.toLowerCase())), `hermes settings: grouped by section (${groups.join(' | ')})`)
  const puts = () => calls().filter(c => c.path === '/api/config' && c.http === 'PUT')

  // A number: refused outside its range, saved inside it, nested under its path; the row shows it and "Changed".
  const retries = pg.locator('.set-row', { hasText: 'Retries before a fallback' })
  check((await retries.innerText()).includes('3'), 'hermes settings: a number shows Hermes’s default')
  await retries.click()
  const sheet = pg.locator('.sheet', { hasText: 'Retries before a fallback' })
  await sheet.getByLabel('Retries before a fallback').fill('42')
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  await sheet.getByText('Between 1 and 10').waitFor({ timeout: 3000 }).then(() => check(true, 'hermes settings: an out-of-range number is refused with its range'), () => check(false, 'hermes settings: an out-of-range number is refused with its range'))
  const before = puts().length
  await sheet.getByLabel('Retries before a fallback').fill('1')
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  await sheet.waitFor({ state: 'detached', timeout: 5000 })
  {
    const put = puts().pop()
    check(puts().length === before + 1 && put.body.config.agent.api_max_retries === 1 && /profile=default/.test(put.query), `hermes settings: saving writes the nested value for the bot (${JSON.stringify(put?.body)})`)
    await pg.locator('.set-row', { hasText: 'Retries before a fallback' }).getByText('Changed').waitFor({ timeout: 5000 }).then(() => check(true, 'hermes settings: a changed option is marked'), () => check(false, 'hermes settings: a changed option is marked'))
  }
  // Use default puts Hermes's default back.
  await pg.locator('.set-row', { hasText: 'Retries before a fallback' }).click()
  await sheet.locator('.set-row', { hasText: 'Use default' }).click()
  check((await sheet.getByLabel('Retries before a fallback').inputValue()) === '3', 'hermes settings: Use default fills in Hermes’s default')
  await sheet.getByRole('button', { name: 'Save', exact: true }).click()
  await sheet.waitFor({ state: 'detached', timeout: 5000 })
  check(puts().pop().body.config.agent.api_max_retries === 3, 'hermes settings: the default is saved back')
  await sleep(300)
  check((await pg.locator('.set-row', { hasText: 'Retries before a fallback' }).getByText('Changed').count()) === 0, 'hermes settings: back at the default, the mark goes')

  // A percentage, and a nullable number ("No limit" writes null).
  await pg.locator('.set-row', { hasText: 'Compress at' }).click()
  const pct = pg.locator('.sheet', { hasText: 'Compress at' })
  check((await pct.getByLabel('Compress at').inputValue()) === '50', 'hermes settings: a ratio is edited as a percentage')
  await pct.getByLabel('Compress at').fill('80')
  await pct.getByRole('button', { name: 'Save', exact: true }).click()
  await pct.waitFor({ state: 'detached', timeout: 5000 })
  check(puts().pop().body.config.compression.threshold === 0.8, 'hermes settings: 80 % is saved as 0.8')
  await pg.locator('.set-row', { hasText: 'Most steps per reply' }).click()
  const steps = pg.locator('.sheet', { hasText: 'Most steps per reply' })
  check(await steps.getByRole('switch', { name: 'No limit' }).getAttribute('aria-checked') === 'true', 'hermes settings: no limit by default')
  await steps.getByRole('switch', { name: 'No limit' }).click()
  await steps.getByLabel('Most steps per reply').fill('60')
  await steps.getByRole('button', { name: 'Save', exact: true }).click()
  await steps.waitFor({ state: 'detached', timeout: 5000 })
  check(puts().pop().body.config.agent.max_turns === 60, 'hermes settings: a limit can be set')
  await pg.locator('.set-row', { hasText: 'Most steps per reply' }).click()
  await steps.locator('.set-row', { hasText: 'Use default' }).click()
  await steps.getByRole('button', { name: 'Save', exact: true }).click()
  await steps.waitFor({ state: 'detached', timeout: 5000 })
  check(puts().pop().body.config.agent.max_turns === null, 'hermes settings: back to No limit writes null')

  // A switch saves at once; a choice; a list; Apply to all bots.
  await pg.locator('.set-row', { hasText: 'File checkpoints' }).getByRole('switch').click()
  await sleep(300)
  check(puts().pop().body.config.checkpoints.enabled === true, 'hermes settings: a switch saves at once')
  await pg.locator('.set-row', { hasText: 'Check work before finishing' }).click()
  const ch = pg.locator('.sheet', { hasText: 'Check work before finishing' })
  await ch.locator('.picker-opt', { hasText: 'For coding' }).click()
  await ch.getByRole('button', { name: 'Save', exact: true }).click()
  await ch.waitFor({ state: 'detached', timeout: 5000 })
  check(puts().pop().body.config.agent.verify_on_stop === 'auto', 'hermes settings: a choice saves its Hermes value')
  await pg.locator('.set-row', { hasText: 'Always blocked commands' }).click()
  const ls = pg.locator('.sheet', { hasText: 'Always blocked commands' })
  await ls.getByLabel('Always blocked commands').fill('rm -rf /*\n\nshutdown *')
  await ls.getByRole('switch', { name: 'Apply to all bots' }).click()
  await ls.getByRole('button', { name: 'Save', exact: true }).click()
  await ls.waitFor({ state: 'detached', timeout: 5000 })
  check(JSON.stringify(puts().pop().body.config.approvals.deny) === '["rm -rf /*","shutdown *"]', 'hermes settings: a list is one item per line')
  check((await pg.locator('.set-row', { hasText: 'Always blocked commands' }).innerText()).includes('2 items'), 'hermes settings: the list row counts its items')
  // Time zone: only zones Hermes knows.
  await pg.locator('.set-row', { hasText: 'Time zone' }).click()
  const tz = pg.locator('.sheet', { hasText: 'Time zone' })
  await tz.getByLabel('Time zone').fill('Mars/Base')
  await tz.getByRole('button', { name: 'Save', exact: true }).click()
  await tz.getByText('Not one Hermux knows').waitFor({ timeout: 3000 }).then(() => check(true, 'hermes settings: an unknown time zone is refused'), () => check(false, 'hermes settings: an unknown time zone is refused'))
  await tz.getByRole('button', { name: 'Cancel' }).click()
  // Put back what this file changed, for later files.
  await fetch(require('../lib.cjs').MOCK + '/api/config', { method: 'PUT', body: JSON.stringify({ config: { compression: { threshold: 0.5 }, checkpoints: { enabled: false }, agent: { verify_on_stop: false }, approvals: { deny: [] } } }) })
  // Settings search: live results, a result opens its page and flashes the row.
  await pg.goto(WEB + '/')
  await pg.getByPlaceholder('Message Hermux').waitFor({ timeout: 15000 })
  await pg.getByRole('button', { name: /^Sessions/ }).click()
  await pg.locator('.nav-tile', { hasText: 'Settings' }).click()
  const find = pg.getByLabel('Search settings')
  await find.fill('checkpoint')
  await pg.locator('.set-row', { hasText: 'File checkpoints' }).first().waitFor({ timeout: 3000 }).then(() => check(true, 'settings search: results show while typing'), () => check(false, 'settings search: results show while typing'))
  await pg.locator('.set-row', { hasText: 'File checkpoints' }).first().click()
  await pg.locator('.hit-flash').first().waitFor({ timeout: 4000 }).then(() => check(true, 'settings search: the chosen setting is flashed on its page'), () => check(false, 'settings search: the chosen setting is flashed on its page'))
  check((await pg.locator('.hit-flash').first().innerText()).includes('File checkpoints'), 'settings search: the flashed row is the chosen one')
  await pg.close()
}
