// Draws the Hermux launcher icon (a caduceus between two arrows, `> <`, in gold) and writes
// android/icon/hermux-icon.svg, then renders the five ic_launcher_fg.png sizes from it.
//   node tools/icon/make-icon.cjs          draw the SVG and the PNGs
//   node tools/icon/make-icon.cjs --png    only the PNGs, from the SVG as committed
// The PNGs are rendered with Playwright's Chromium (from tools/web-e2e/node_modules; run tools/setup.sh first).
// Design space is 100 x 100; the mark is scaled to fit inside the adaptive icon's 66 dp safe zone.
const fs = require('fs'), path = require('path')
const ROOT = path.join(__dirname, '..', '..')
const SVG = path.join(ROOT, 'android', 'icon', 'hermux-icon.svg')
const GOLD = '#d9a441', DARK = '#0e1115'

const dia=(y,r,c)=>`<path d="M50 ${y-r}L${50+r*.8} ${y}L50 ${y+r}L${50-r*.8} ${y}Z" fill="${c}"/>`;
const ss=(a,b,x)=>{const t=Math.min(1,Math.max(0,(x-a)/(b-a)));return t*t*(3-2*t)};
function line(s,o){const pts=[];const hx=50+s*o.amp;
 const P0=[hx,o.top],P1=[hx,o.top-o.hl*.75],P2=[50+s*(o.hin+4),o.top-o.hl],P3=[50+s*o.hin,o.top-o.hl*.45];
 for(let i=60;i>=0;i--){const u=i/60,v=1-u;pts.push([v*v*v*P0[0]+3*v*v*u*P1[0]+3*v*u*u*P2[0]+u*u*u*P3[0],v*v*v*P0[1]+3*v*v*u*P1[1]+3*v*u*u*P2[1]+u*u*u*P3[1],-v-.0001])}
 const n=400;for(let i=1;i<=n;i++){const y=o.top+(o.bot-o.top)*i/n,t=(y-o.top)/(o.bot-o.top);const a=o.amp*(1-o.narrow*t);pts.push([50+s*a*Math.cos(Math.PI*(y-o.top)/o.P),y,t])}
 return pts}
function hw(p,o){const t=p[2];if(t<0){const u=-t;return o.w/2*(1+.28*Math.sin(Math.PI*u))*(u<.42?Math.pow(u/.42,.8):1)}return o.w/2*(1-.94*ss(o.tap,1,t))}
function outline(pts,o,a,b,extra){const L=[],R=[];for(let i=a;i<=b;i++){const p=pts[Math.max(0,i-1)],q=pts[Math.min(pts.length-1,i+1)];let dx=q[0]-p[0],dy=q[1]-p[1];const n=Math.hypot(dx,dy)||1;dx/=n;dy/=n;const h=hw(pts[i],o)+(extra||0);L.push([pts[i][0]+dy*h,pts[i][1]-dx*h]);R.unshift([pts[i][0]-dy*h,pts[i][1]+dx*h])}return'M'+L.concat(R).map(p=>p[0].toFixed(2)+' '+p[1].toFixed(2)).join('L')+'Z'}
function cad(o,c,b){let h=`<path d="M${50-o.sw/2} ${o.st}H${50+o.sw/2}V${o.sb-5}L50 ${o.sb}L${50-o.sw/2} ${o.sb-5}Z" fill="${c}"/>`;
 const S={1:line(1,o),'-1':line(-1,o)};
 for(const s of[1,-1])h+=`<path d="${outline(S[s],o,0,S[s].length-1)}" fill="${c}"/>`;
 let i=0;for(let y=o.top+o.P/2;y<o.bot;y+=o.P){const s=i%2?-1:1,pts=S[s],k=pts.findIndex(p=>p[2]>=0&&p[1]>=y);const span=Math.round(o.gap/(o.bot-o.top)*400);
  h+=`<path d="${outline(pts,o,k-span,Math.min(pts.length-1,k+span),o.cas)}" fill="${b}"/><path d="${outline(pts,o,k-span-8,Math.min(pts.length-1,k+span+8))}" fill="${c}"/>`;i++}
 return h}
const HELIX={amp:13,top:36,P:14.8,bot:85,w:5.2,gap:4,cas:1.4,sw:3.8,st:16,sb:93,hl:8.5,hin:4.2,narrow:.2,tap:.62};
function feather(s,B,ang,len,wd,round,c,b){const a=ang*Math.PI/180,d=[s*Math.cos(a),-Math.sin(a)],n=[-d[1],d[0]];
 const P=(t,k)=>[B[0]+d[0]*len*t+n[0]*wd*k,B[1]+d[1]*len*t+n[1]*wd*k],f=p=>p[0].toFixed(2)+' '+p[1].toFixed(2);
 const a1=P(0,.5),a2=P(.78,.5),tip=P(1,0),b2=P(.78,-.5),b1=P(0,-.5);
 const body=round?`M${f(a1)}L${f(a2)}Q${f(P(1.02,.5))} ${f(tip)}Q${f(P(1.02,-.5))} ${f(b2)}L${f(b1)}Z`:`M${f(a1)}L${f(a2)}L${f(tip)}L${f(b2)}L${f(b1)}Z`;
 return `<path d="${body}" fill="${c}" stroke="${b}" stroke-width="1.1" paint-order="stroke"/>`}
function wing(s,o,c,b){const R=[50+s*2.6,o.y];let h='';
 for(let i=o.n-1;i>=0;i--){const t=i/(o.n-1);h+=feather(s,[R[0],R[1]+t*o.drop],o.a0+(o.a1-o.a0)*t,o.L*(1-o.shrink*t),o.fw,o.round,c,b)}
 const a=o.a0*Math.PI/180,tx=R[0]+s*Math.cos(a)*o.L*o.arm,ty=R[1]-Math.sin(a)*o.L*o.arm;
 h+=`<path d="M${R[0]} ${R[1]-1.5}Q${(R[0]+tx)/2} ${ty-3} ${tx} ${ty}Q${(R[0]+tx)/2+s*1} ${(R[1]+ty)/2+4} ${R[0]} ${R[1]+o.drop*.7}Z" fill="${c}" stroke="${b}" stroke-width="1.1" paint-order="stroke"/>`;
 return h}
const WA={y:20,n:5,drop:4,a0:38,a1:-8,L:26,shrink:.45,fw:4.2,round:false,arm:.55};
const CAD=(c,b)=>cad(HELIX,c,b)+wing(1,WA,c,b)+wing(-1,WA,c,b)+dia(10,6.5,c);
const mir=g=>g+`<g transform="translate(100 0) scale(-1 1)">${g}</g>`;
const arrows=c=>mir(`<path d="M7 33L23 50L7 67" fill="none" stroke="${c}" stroke-width="9" stroke-linejoin="miter" stroke-miterlimit="10"/>`);

// White where the mark is, black in the gaps between feathers and serpents: the gaps end up transparent,
// so the themed (monochrome) icon keeps them too.
const mark=(c,b)=>`<g transform="translate(54 54) scale(${30/51}) translate(-50 -50)">${CAD(c,b)+arrows(c)}</g>`
const svg=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">
<!-- Hermux launcher icon, foreground layer. Generated by tools/icon/make-icon.cjs. The background layer is the colour icon_bg (${DARK}). -->
<mask id="m" maskUnits="userSpaceOnUse" x="0" y="0" width="108" height="108"><rect width="108" height="108" fill="#000"/>${mark('#fff','#000')}</mask>
<rect width="108" height="108" fill="${GOLD}" mask="url(#m)"/>
</svg>
`

function renderPngs(){
  const { chromium } = require(path.join(ROOT, 'tools', 'web-e2e', 'node_modules', 'playwright'))
  const sizes = { mdpi: 108, hdpi: 162, xhdpi: 216, xxhdpi: 324, xxxhdpi: 432 }
  const src = fs.readFileSync(SVG, 'utf8')
  return (async () => {
    const exe = process.env.CHROMIUM || undefined
    const b = await chromium.launch(exe ? { executablePath: exe } : {})
    for (const [d, px] of Object.entries(sizes)) {
      const p = await b.newPage({ viewport: { width: px, height: px } })
      await p.setContent(`<body style="margin:0;background:transparent"><div style="width:${px}px;height:${px}px">${src.replace('width="108" height="108"', `width="${px}" height="${px}"`)}</div></body>`)
      const out = path.join(ROOT, 'android', 'res', `mipmap-${d}`, 'ic_launcher_fg.png')
      await p.screenshot({ path: out, omitBackground: true })
      console.log('wrote', path.relative(ROOT, out))
      await p.close()
    }
    await b.close()
  })()
}

if (!process.argv.includes('--png')) { fs.writeFileSync(SVG, svg); console.log('wrote', path.relative(ROOT, SVG)) }
renderPngs().catch(e => { console.error(e); process.exit(1) })
